# Bake accelerometer hwdb into hwdb.bin (loose .hwdb files are ignored until compiled)
starlite_refresh_hwdb() {
  local img="$1"
  local u="$W/udev-root"
  rm -rf "$u"
  mkdir -p "$u/etc/udev"
  guestfish --ro -a "$img" -m /dev/sda3:/ <<GF 2>/dev/null || die "could not read image hwdb"
download /etc/udev/hwdb.bin $u/etc/udev/hwdb.bin
copy-out /etc/udev/hwdb.d $u/etc/udev
GF
  # Host compiles hwdb with our StarLite entries
  if command -v systemd-hwdb >/dev/null; then
    systemd-hwdb --root="$u" update 2>/dev/null || systemd-hwdb update --root="$u" 2>/dev/null || true
  elif command -v udevadm >/dev/null; then
    udevadm hwdb --update --root="$u" 2>/dev/null || true
  fi
  if [ -s "$u/etc/udev/hwdb.bin" ]; then
    guestfish --rw -a "$img" -m /dev/sda3:/ \
      upload "$u/etc/udev/hwdb.bin" /etc/udev/hwdb.bin 2>/dev/null || true
    if strings "$u/etc/udev/hwdb.bin" | grep -F -q 'MXC6655:MXC6655::'; then
      ok "hwdb.bin contains the double-colon MXC6655 key"
    else
      die "hwdb.bin is missing acpi:MXC6655:MXC6655:: — rotation would not bind"
    fi
  else
    die "hwdb.bin was not produced"
  fi
}

lean_strip_fyde_extras() {
  local img="$1"
  say "lean) strip Fyde AI/extras (keep ARC + Crostini + Files + Player)"

  # Host-side staging for small policy / edited files we upload back
  local L="$W/lean"; mkdir -p "$L"

  # 1) Pull files we may edit
  guestfish --ro -a "$img" -m /dev/sda3:/ <<GF 2>/dev/null || true
download /etc/fydeos_scripts/list $L/fydeos_scripts.list
download /etc/chrome_dev.conf $L/chrome_dev.conf
GF

  # 2) Edit fydeos_scripts list: drop ota-checker + backup; keep hwtuner
  if [ -s "$L/fydeos_scripts.list" ]; then
    grep -vE '^(fydeos-ota-checker|fydeos-backup)$' "$L/fydeos_scripts.list" > "$L/fydeos_scripts.list.new" || true
    mv "$L/fydeos_scripts.list.new" "$L/fydeos_scripts.list"
    ok "fydeos_scripts/list: removed ota-checker + backup (kept hwtuner if present)"
  fi

  # 3) chrome_dev.conf: drop fyde-auto-signin-delay; keep ARC flags
  if [ -s "$L/chrome_dev.conf" ]; then
    sed -E 's/(^|[[:space:]])--fyde-auto-signin-delay=[^[:space:]]+//g' "$L/chrome_dev.conf" \
      | sed 's/  */ /g' > "$L/chrome_dev.conf.new"
    mv "$L/chrome_dev.conf.new" "$L/chrome_dev.conf"
    ok "chrome_dev.conf: removed --fyde-auto-signin-delay=* (ARC flags preserved)"
  fi

  # 4) Block Fyde account apps only.
  # Keep Gallery, Files, Camera, and the RIME input method.
  # Gallery is the Chrome system media app, not one of these ids.
  mkdir -p "$L/policies"
  cat > "$L/policies/starlite_lean_extensions.json" <<'JSON'
{
  "ExtensionInstallBlocklist": [
    "fogdcaodknbhigpklbhepedofamkfbln",
    "hidnajblbifdkmheebalalchohohmaef",
    "mofiofjpikncjaigmdlblhojbnkabako"
  ],
  "URLBlocklist": [
    "https://notes.fydeos.io/*",
    "https://ai.fydeos.io/*",
    "chrome://fydeos-ai/*",
    "https://rdp.fydeos.io/*"
  ],
  "WebAppSettings": [
    {
      "manifest_id": "https://notes.fydeos.io/",
      "installation_mode": "blocked"
    },
    {
      "manifest_id": "https://notes.fydeos.io/?source=pwa",
      "installation_mode": "blocked"
    },
    {
      "manifest_id": "https://ai.fydeos.io/",
      "installation_mode": "blocked"
    },
    {
      "manifest_id": "https://ai.fydeos.io/chat/",
      "installation_mode": "blocked"
    }
  ]
}
JSON
  if grep -E -q 'media-app|file-manager|camera-app' "$L/policies/starlite_lean_extensions.json"; then
    die "lean policy would block Gallery, Files, or Camera"
  fi

  # 5) Apply removals + uploads inside ROOT-A
  guestfish --rw -a "$img" -m /dev/sda3:/ <<GF 2>&1 | grep -v '^$' | sed 's/^/    /'
# Default Fyde CRX validation + matching crx (do not remove empty parent dirs)
glob rm-f /usr/share/import_extensions/fogdcaodknbhigpklbhepedofamkfbln-*.crx
glob rm-f /usr/share/import_extensions/mofiofjpikncjaigmdlblhojbnkabako-*.crx
glob rm-f /usr/share/import_extensions/validation/fogdcaodknbhigpklbhepedofamkfbln*
glob rm-f /usr/share/import_extensions/validation/mofiofjpikncjaigmdlblhojbnkabako*
glob rm-f /usr/share/import_extensions/hidnajblbifdkmheebalalchohohmaef-*.crx
glob rm-f /usr/share/import_extensions/validation/hidnajblbifdkmheebalalchohohmaef*

# Force-installed Fyde account apps: App Store, System Controller, Remote Desktop.
# The RIME input method (nfglebjgiflmmcdddkbcbgmdkomlfcpa) stays.
rm-f /usr/share/chromium/extensions/fogdcaodknbhigpklbhepedofamkfbln.json
rm-f /usr/share/chromium/extensions/hidnajblbifdkmheebalalchohohmaef.json
rm-f /usr/share/chromium/extensions/mofiofjpikncjaigmdlblhojbnkabako.json

# Optional Fyde remote helpers
rm-rf /usr/share/remote-help
rm-rf /usr/share/novnc

# Optional OTA / backup content (keep dirs if present by emptying via rm-rf of known trees)
rm-rf /usr/share/fydeos-ota-checker
rm-rf /usr/share/fydeos-backup

# Upload edited lists / conf if we staged them
GF

  # Drop Fyde account CRXs from the import list. Keep the RIME IME and Everdroid lines.
guestfish --ro -a "$img" -m /dev/sda3:/ \
  download /usr/share/import_extensions/validation/fydeos-default-apps-1.0.0.validation \
  "$L/fydeos-default-apps.validation" 2>/dev/null || true
if [ -s "$L/fydeos-default-apps.validation" ]; then
  grep -vE 'fogdcaodknbhigpklbhepedofamkfbln|hidnajblbifdkmheebalalchohohmaef|mofiofjpikncjaigmdlblhojbnkabako' \
    "$L/fydeos-default-apps.validation" > "$L/fydeos-default-apps.validation.new" || true
  mv "$L/fydeos-default-apps.validation.new" "$L/fydeos-default-apps.validation"
  guestfish --rw -a "$img" -m /dev/sda3:/ \
    upload "$L/fydeos-default-apps.validation" \
    /usr/share/import_extensions/validation/fydeos-default-apps-1.0.0.validation \
    2>/dev/null || true
  ok "default-apps list no longer imports Store, System Controller, or Remote Desktop"
fi

# Upload edited files only if we have them (separate guestfish for clarity)
  if [ -s "$L/fydeos_scripts.list" ]; then
    guestfish --rw -a "$img" -m /dev/sda3:/ <<GF 2>/dev/null
mkdir-p /etc/fydeos_scripts
upload $L/fydeos_scripts.list /etc/fydeos_scripts/list
GF
  fi
  if [ -s "$L/chrome_dev.conf" ]; then
    guestfish --rw -a "$img" -m /dev/sda3:/ \
      upload "$L/chrome_dev.conf" /etc/chrome_dev.conf 2>/dev/null || true
  fi
  guestfish --rw -a "$img" -m /dev/sda3:/ <<GF 2>/dev/null
mkdir-p /etc/opt/chrome/policies/managed
upload $L/policies/starlite_lean_extensions.json /etc/opt/chrome/policies/managed/starlite_lean_extensions.json
GF

  ok "lean strip applied (ARC/Crostini/Files untouched)"
}

say "1) copy base image"
cp --reflink=auto "$IN" "$OUT" || die "copy failed"
ok "$OUT"

say "2) partition geometry + detect image KVER"
ROOTA_START=$(sgdisk -i 3 "$OUT" | grep -o 'First sector: [0-9]*' | awk '{print $3}')
KA_START=$(sgdisk -i 2 "$OUT" | grep -o 'First sector: [0-9]*' | awk '{print $3}')
KA_SIZE=$(sgdisk -i 2 "$OUT" | grep -oE 'Partition size: [0-9]*' | awk '{print $3}')
KB_START=$(sgdisk -i 4 "$OUT" | grep -o 'First sector: [0-9]*' | awk '{print $3}')
KB_SIZE=$(sgdisk -i 4 "$OUT" | grep -oE 'Partition size: [0-9]*' | awk '{print $3}')
ROOTA_OFF=$((ROOTA_START * 512))
# ROOT-A payload size comes from the grub dm= line: "0 <sectors> verity ..."
guestfish --ro -a "$OUT" -m /dev/sda12:/ download /efi/boot/grub.cfg "$W/grub.cfg" 2>/dev/null || die "no grub.cfg"
PAY_SECTORS=$(grep -o 'ro 1,0 [0-9]*' "$W/grub.cfg" | head -1 | awk '{print $3}')
PAY_BLOCKS=$((PAY_SECTORS / 8))
PAY_BYTES=$((PAY_SECTORS * 512))
SALT=$(grep -o 'salt=[0-9a-f]*' "$W/grub.cfg" | head -1 | cut -d= -f2)
OLD=$(grep -o 'root_hexdigest=[0-9a-f]*' "$W/grub.cfg" | head -1 | cut -d= -f2)
ok "ROOT-A @sector $ROOTA_START  payload ${PAY_BLOCKS}x4K  salt ${SALT:0:16}…"
ok "current grub digest ${OLD:0:16}…"

starlite_print_identity "$OUT"
KVER=$IMAGE_KVER
ok "image KVER=$KVER ($IMAGE_FAMILY)"
export STARLITE_SKIP_MXC=$SKIP_MXC
# Do not compile a module here. A wrong kernel tree would not load, and
# replacing vmlinuz is not allowed. The cache must already match this KVER.
starlite_select_mxc_ko "$KVER"
MXC_SKIP=${MXC_SKIP:-0}
if [ "${MXC_SKIP:-0}" != 1 ]; then
  starlite_check_trigger_name "$IMAGE_FAMILY" "$MXC_KO"
fi

# MXC_KO + MXC_VERMAGIC now set

say "3) PROOF-OF-METHOD — reproduce the EXISTING digest before trusting anything"
# ChromeOS uses dm-bht, NOT upstream dm-verity: veritysetup gives the WRONG digest.
dd if="$OUT" of="$W/roota.img" bs=512 skip="$ROOTA_START" count="$PAY_SECTORS" status=none
GOT=$("$TOOLS/run_verity.sh" mode=create alg=sha256 payload="$W/roota.img" \
      payload_blocks="$PAY_BLOCKS" hashtree="$W/h0.img" salt="$SALT" 2>/dev/null \
      | grep -o 'root_hexdigest=[0-9a-f]*' | cut -d= -f2)
HASHSTART=$(grep -o 'hashstart=[0-9]*' "$W/grub.cfg" | head -1 | cut -d= -f2)
ROOTA_SECTORS=$(sgdisk -i 3 "$OUT" | grep -oE 'Partition size: [0-9]*' | awk '{print $3}')
if [ "$GOT" = "$OLD" ]; then
  ok "reproduced $GOT — method trusted"
elif [ -n "$GOT" ] && [ "$HASHSTART" = "$PAY_SECTORS" ] && [ "${#SALT}" -eq 64 ] \
     && [ "${#GOT}" -eq 64 ] && [ "$PAY_SECTORS" -lt "$ROOTA_SECTORS" ]; then
  # Stock OpenFyde ships a digest that is not the hash of ROOT-A. The image
  # still boots because dm_verity.error_behavior=3. The size and salt above
  # are the values the bootloader will use, so the re-seal publishes the
  # digest of the bytes we ship. OLD stays the published string so it can be
  # replaced in grub and both kernel slots.
  echo "  WARN: published digest ${OLD:0:16}… is not the hash of this ROOT-A (${GOT:0:16}…)."
  echo "        Boot-line size and salt check out. The re-seal will publish the real digest."
else
  die "PROOF FAILED: recomputed $GOT != grub's $OLD — parameters wrong, ABORT"
fi

say "4) inject StarLite fixes into ROOT-A (KVER=$KVER)"
# ChromeOS ext2 RO-compat marker must be cleared or guestfish --rw fails "bad superblock"
printf '\x00' | dd of="$OUT" bs=1 seek=$((ROOTA_OFF + 0x467)) count=1 conv=notrunc status=none
ok "cleared ext2 RO marker"

# Host-side modules.dep snippet (appended if depmod unavailable in guest)
MXC_REL="kernel/drivers/iio/accel/mxc4005.ko"
printf '%s:\n' "$MXC_REL" > "$W/mxc4005.modules.dep.line"

if [ "${MXC_SKIP:-0}" != "1" ]; then
  guestfish --rw -a "$OUT" -m /dev/sda3:/ <<GFMXC 2>&1 | grep -v '^$' | sed 's/^/    /'
mkdir-p /lib/modules/$KVER/kernel/drivers/iio/accel
upload $MXC_KO /lib/modules/$KVER/kernel/drivers/iio/accel/mxc4005.ko
chmod 0644 /lib/modules/$KVER/kernel/drivers/iio/accel/mxc4005.ko
GFMXC
  ok "uploaded mxc4005.ko for $KVER"
else
  ok "skipped mxc4005.ko upload (--skip-mxc)"
fi

guestfish --rw -a "$OUT" -m /dev/sda3:/ <<GF 2>&1 | grep -v '^$' | sed 's/^/    /'
upload $SRCDIR/power-sleep /usr/sbin/power-sleep
upload $SRCDIR/power-sleep.sh /usr/sbin/power-sleep.sh
upload $SRCDIR/edp-resume-fix.sh /usr/sbin/edp-resume-fix.sh
upload $SRCDIR/tablet-switch /usr/sbin/tablet-switch
upload $SRCDIR/lid-touch-guard.sh /usr/sbin/lid-touch-guard.sh
upload $SRCDIR/external-only-guard.sh /usr/sbin/external-only-guard.sh
upload $SRCDIR/install-to-internal /usr/sbin/install-to-internal
upload $SRCDIR/power-sleep.conf /etc/init/power-sleep.conf
upload $SRCDIR/edp-resume.conf /etc/init/edp-resume.conf
upload $SRCDIR/tablet-switch.conf /etc/init/tablet-switch.conf
upload $SRCDIR/lid-touch-guard.conf /etc/init/lid-touch-guard.conf
upload $SRCDIR/external-only-guard.conf /etc/init/external-only-guard.conf
upload $SRCDIR/load-mxc4005.conf /etc/init/load-mxc4005.conf
mkdir-p /lib/modules/$KVER/kernel/drivers/iio/accel
mkdir-p /etc/udev/hwdb.d
