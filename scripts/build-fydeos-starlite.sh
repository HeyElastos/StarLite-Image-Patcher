
ensure_tpm_hide_cmdline() {
  # $1 = text file with linux cmdline (grub.cfg / usb.A.cfg / kern cfg)
  local f="$1"
  [ -f "$f" ] || return 0
  if ! grep -q 'tpm_tis.force=0' "$f"; then
    sed -i 's/console= /console= tpm_tis.force=0 /g' "$f" || true
  fi
  if ! grep -q 'modprobe.blacklist=tpm_tis,tpm_crb' "$f"; then
    sed -i 's/tpm_tis.force=0/tpm_tis.force=0 modprobe.blacklist=tpm_tis,tpm_crb/' "$f" || true
  fi
}
#!/usr/bin/env bash
# build-fydeos-starlite.sh — turn a FydeOS or OpenFyde iris image into a
# StarLite image that boots verified, keeps Android/WiFi, carries every StarLite
# hardware fix, AND installs from the on-screen GUI button.
#
# The image's own /etc/lsb-release and /lib/modules decide the product and the
# kernel. The accelerometer module is chosen for that kernel. The kernel in
# the image is not replaced.
#
#   ./scripts/build-fydeos-starlite.sh [--lean|--no-lean] [--identify] <image.bin> [output.bin]
#
# Defaults: --lean ON (strip Fyde AI/extras; keep Files, ARC/fyDroid, Crostini, player).
# Escape hatch: --no-lean
#
# Proven 2026-08-07 on FydeOS iris R144 (16503.20.22.24): GUI install, Wi-Fi,
# tablet mode and Android all confirmed working on-device.
#
# Latest StarLite fixes injected from out/release/sources/ (as of 2026-09-20):
#   - mxc4005.ko (per-KVER: detect /lib/modules/*; refuse wrong vermagic) +
#       load-mxc4005.conf + starlite-mxc4005.conf + 61-starlite-accel.hwdb
#   - edp-resume-fix.sh  (remember last brightness via /var/lib/starlite-last-brightness)
#   - lid-touch-guard.sh  (unbind Goodix when lid closed; honors external-only flag)
#   - external-only-guard.sh  (force eDP off + unbind touch when user disables
#       internal display while HDMI/USB-C connected — case without keyboard)
#   - tablet-switch, power-sleep, install-to-internal
#   - i915.enable_dpcd_backlight=0 baked into grub/kernel cmdline (verity re-seal)
#   - optional lean_strip_fyde_extras (see docs/LEAN-STARLITE.md)
#
# ---------------------------------------------------------------------------
# WHY THE GUI INSTALL BREAKS IF YOU SKIP THE RE-SEAL  (the bug that cost weeks)
#
# The verity root digest lives in FOUR places. Modifying ROOT-A changes its real
# hash, and every copy must be updated or the install dies:
#
#   1. ROOT-A's own hashtree            (regenerated by the re-seal)
#   2. /efi/boot/grub.cfg   on the ESP  <- the ONLY one updated originally
#   3. KERN-A *and* KERN-B vboot config <- MISSED -> cros_installer aborts
#   4. /syslinux/usb.A.cfg  on the ESP  <- MISSED
#
# cros_installer reads the digest out of the KERNEL config to extract the verity
# arguments. Stale digest -> hard fail -> postinst aborts. And chromeos-postinst
# DISCARDS cros_installer's exit status, so the GUI can report success on a disk
# that never got installed. That silent failure is why this took so long to find.
#
# BOTH kernel slots must be patched: the installed KERN-A is copied from the
# SOURCE KERN-B, so fixing only partition 2 leaves the install broken.
#
# Do NOT touch grub's "verified image B" entry: it references ROOT-B's own
# PARTUUID, and ROOT-B is never modified, so its stock digest is CORRECT there.
# Patching it breaks the B slot.
#
# Myth, now disproven: chromeos-install does NOT rebuild a pristine rootfs. It
# block-copies ROOT-A with dd. The GUI installer was never the villain.
# ---------------------------------------------------------------------------
